"""Assess whether instruction-file composition records carry useful information.

An automatically prepared instruction file may contain placeholder SFAC/UNIT records. This
module checks declaration consistency and provenance signals; it does not infer a compound.
For example, equal counts across several elements warrant review, and an owner-declared element
missing from SFAC makes the declaration incomplete. Counts that are multiples of Z are normal.

Documentation and regression examples are hand-authored synthetic examples. Private case
compositions and expert-model excerpts belong only in local, ignored acceptance evidence.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass

__all__ = [
    "CompositionSignal",
    "CompositionTrust",
    "assess_composition",
    "AUTO_PIPELINE_MARKERS",
]

#: ``REM`` text that identifies a machine-written instruction file. Matched case-insensitively as a
#: substring, because vendors vary the wording between versions.
AUTO_PIPELINE_MARKERS: tuple[str, ...] = (
    "ins file created by",
    "crysalispro",
    "rigaku oxford diffraction",
    "created by apex",
    "bruker axs",
    "generated by olex2",
    "in standard setting",
)


class CompositionSignal(str, enum.Enum):
    """Why the composition is not believed. Several may fire at once."""

    ALL_COUNTS_EQUAL = "all_counts_equal"
    """Every element has the same ``UNIT`` count across two or more elements. A real compound
    essentially never does this; a placeholder always does."""

    PRE_SOLUTION_VENDOR_FILE = "pre_solution_vendor_file"
    """The file was written by an instrument pipeline and contains no atoms yet.

    This is a fact about provenance, not a heuristic: a vendor file generated *before* the
    structure was solved cannot know the composition, because nobody knew it. Whatever is in
    ``SFAC``/``UNIT`` was put there so that direct methods had something to start from.

    A vendor file that has since been refined -- one that *does* carry atom records -- is not
    caught by this, because a human has been through it.
    """

    NO_ELEMENT_HEAVIER_THAN_OXYGEN = "no_element_heavier_than_oxygen"
    """``SFAC`` is a subset of the organic set. Suspicious on its own only in combination, but
    decisive when the crystallographer has declared a metal that is absent from the file."""

    DECLARED_METAL_ABSENT = "declared_metal_absent"
    """The crystallographer named a metal that the file's ``SFAC`` does not contain. The file is
    then definitively incomplete, whatever else is true of it."""

    DECLARED_ELEMENT_ABSENT = "declared_element_absent"
    """A non-metal the crystallographer expects is missing from ``SFAC``.

    A synthetic SFAC list containing only C, Cu, N and O cannot represent a declared chloride
    component. A solver cannot assign a missing element through this declaration, so the
    omission needs explicit review before interpreting unassigned density.

    Blocking for the same reason as a missing metal: the file cannot describe the compound.
    """

    MACHINE_WRITTEN = "machine_written"
    """A ``REM`` record naming the vendor pipeline that wrote the file."""

    SFAC_UNIT_LENGTH_MISMATCH = "sfac_unit_length_mismatch"
    """``SFAC`` and ``UNIT`` disagree in length, so the file is malformed regardless."""


@dataclass(frozen=True)
class CompositionTrust:
    """Whether the ``SFAC``/``UNIT`` records may be used as evidence."""

    trusted: bool
    signals: tuple[CompositionSignal, ...]
    detail: str
    elements: tuple[str, ...]
    z: int | None = None
    missing_declared_metals: tuple[str, ...] = ()
    missing_declared_elements: tuple[str, ...] = ()

    @property
    def is_placeholder(self) -> bool:
        return not self.trusted

    def as_inputs(self) -> dict[str, str]:
        """Flat strings for a selection-rule ``inputs`` map."""
        return {
            "composition_trusted": str(self.trusted).lower(),
            "composition_signals": ",".join(s.value for s in self.signals) or "none",
            "sfac": " ".join(self.elements) or "none",
        }


def assess_composition(
    *,
    sfac: tuple[str, ...],
    unit: tuple[float, ...],
    z: int | None,
    rem_lines: tuple[str, ...] = (),
    declared_metals: tuple[str, ...] = (),
    declared_elements: tuple[str, ...] = (),
    has_atom_records: bool = False,
) -> CompositionTrust:
    """Decide whether this file's composition carries information.

    ``declared_metals`` is the crystallographer's own prior. When they say the compound contains
    copper and the file's ``SFAC`` does not, that is not a heuristic -- the file is simply missing
    an element, and no amount of other evidence makes it complete.
    """
    signals: list[CompositionSignal] = []
    reasons: list[str] = []

    normalised = tuple(s.strip().capitalize() for s in sfac if s.strip())
    missing = tuple(
        m for m in (d.strip().capitalize() for d in declared_metals) if m and m not in normalised
    )

    missing_other = tuple(
        e
        for e in dict.fromkeys(x.strip().capitalize() for x in declared_elements)
        if e and e not in normalised and e not in missing
    )

    if missing:
        signals.append(CompositionSignal.DECLARED_METAL_ABSENT)
        reasons.append(
            f"you declared the metal {', '.join(missing)} but SFAC lists only "
            f"{' '.join(normalised) or '(nothing)'}, so the file's composition is incomplete"
        )

    if missing_other:
        signals.append(CompositionSignal.DECLARED_ELEMENT_ABSENT)
        reasons.append(
            f"you expect {', '.join(missing_other)} but SFAC does not list "
            f"{'it' if len(missing_other) == 1 else 'them'}; a solution program places atoms only "
            "for elements it was told about, so anything built from the missing ones cannot appear "
            "at all"
        )

    if sfac and unit and len(sfac) != len(unit):
        signals.append(CompositionSignal.SFAC_UNIT_LENGTH_MISMATCH)
        reasons.append(f"SFAC has {len(sfac)} elements but UNIT has {len(unit)} counts")

    if len(unit) >= 2 and len(set(unit)) == 1:
        signals.append(CompositionSignal.ALL_COUNTS_EQUAL)
        reasons.append(
            f"all {len(unit)} UNIT counts are identical ({unit[0]:g}), which is a filled-in field "
            "rather than a composition"
        )

    if normalised and not _has_element_heavier_than_oxygen(normalised):
        signals.append(CompositionSignal.NO_ELEMENT_HEAVIER_THAN_OXYGEN)

    machine_written = _looks_machine_written(rem_lines)
    if machine_written:
        signals.append(CompositionSignal.MACHINE_WRITTEN)

    if machine_written and not has_atom_records:
        signals.append(CompositionSignal.PRE_SOLUTION_VENDOR_FILE)
        per_unit = _per_formula_unit(normalised, unit, z)
        reasons.append(
            "the file was written by the instrument's own pipeline and contains no atoms yet, so "
            "its composition is a starting guess rather than a measurement"
            + (f" (it amounts to '{per_unit}' per formula unit at Z={z})" if per_unit else "")
        )

    # A vendor marker alone is not disqualifying -- a vendor file can be refined by hand into
    # something correct, and then it carries atoms. What is disqualifying is a vendor file that
    # has not been solved yet: at the moment it was written, nobody knew the composition.
    decisive = {
        CompositionSignal.DECLARED_METAL_ABSENT,
        CompositionSignal.DECLARED_ELEMENT_ABSENT,
        CompositionSignal.ALL_COUNTS_EQUAL,
        CompositionSignal.PRE_SOLUTION_VENDOR_FILE,
        CompositionSignal.SFAC_UNIT_LENGTH_MISMATCH,
    }
    trusted = not (decisive & set(signals))

    if trusted:
        detail = "The declared composition shows no sign of being a placeholder."
    else:
        detail = (
            "This composition should not be used as evidence: "
            + "; ".join(reasons)
            + ". Supply the expected elements as a chemical prior instead."
        )

    return CompositionTrust(
        trusted=trusted,
        signals=tuple(dict.fromkeys(signals)),
        detail=detail,
        elements=normalised,
        z=z,
        missing_declared_metals=missing,
        missing_declared_elements=missing_other,
    )


def _per_formula_unit(
    elements: tuple[str, ...], unit: tuple[float, ...], z: int | None
) -> str | None:
    """Render ``UNIT`` divided by Z, for the message only.

    ``UNIT`` is Z times the formula unit by definition, so counts being multiples of Z is entirely
    normal and is **not** evidence of anything -- an earlier version of this module treated it as
    suspicious and rejected a perfectly ordinary composition. It is shown here purely so the
    crystallographer can see what the pipeline assumed.
    """
    if not z or z <= 0 or not unit or len(unit) != len(elements):
        return None
    parts: list[str] = []
    for element, count in zip(elements, unit):
        if count <= 0 or count % z != 0:
            return None
        per = int(count // z)
        parts.append(element if per == 1 else f"{element}{per}")
    return "".join(parts)


def _has_element_heavier_than_oxygen(elements: tuple[str, ...]) -> bool:
    from crystalx_core.domain.chemistry import atomic_number

    for symbol in elements:
        try:
            if atomic_number(symbol) > 8:
                return True
        except KeyError:
            continue
    return False


def _looks_machine_written(rem_lines: tuple[str, ...]) -> bool:
    lowered = [line.lower() for line in rem_lines]
    return any(marker in line for line in lowered for marker in AUTO_PIPELINE_MARKERS)
