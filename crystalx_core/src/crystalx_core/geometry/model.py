"""Model geometry for display: Cartesian coordinates, bonds, and an honest account of what is shown.

Three decisions, each stated because a viewer that gets them wrong looks fine and misleads:

1. **Fractional to Cartesian uses the full cell matrix.** The standard orthogonalisation (a along x,
   b in the xy-plane) is correct for any cell; treating fractional coordinates as if the cell were
   orthogonal distorts every non-90-degree structure, which is most of them.

2. **What is drawn is the asymmetric unit as written in the file.** No symmetry operator is applied.
   That is stated in the payload so the frontend can say it too.

3. **No line is drawn across a cell boundary.** Two atoms within bonding distance only through a
   lattice translation are listed as boundary contacts with their translation and distance, and
   counted, but not drawn -- a line through the middle of the cell between them would be a bond
   that does not exist. Distances are Cartesian, using the full cell metric. The component-wise
   "nearest" image is not the nearest one in a skew cell, so every lattice translation that could
   bring two sites within bonding distance is tried: along axis *i* a contact of length *L* needs
   ``|t_i| <= R_i + L |a*_i|`` (``R_i`` the spread of the sites' fractional coordinates, ``|a*_i|``
   the reciprocal length), which bounds the search exactly (:func:`contact_search_extents`).
   Coverage is still limited, and stated: contacts generated by the space group's other symmetry
   operators are not searched, and both the drawn lines and the listed contacts are a display
   heuristic from covalent radii, not evidence of chemical connectivity.

Confidence is *not* derived from occupancy, displacement parameters or anything else. Until a
calibrated uncertainty estimate exists, every atom is opaque and the payload says confidence is
unavailable, with the reason.
"""

