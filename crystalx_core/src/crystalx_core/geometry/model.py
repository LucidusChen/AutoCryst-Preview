def orthogonalisation_matrix(
    cell: tuple[float, float, float, float, float, float],
) -> tuple[tuple[float, float, float], ...]:
    """Rows of the matrix M with ``cart = M @ frac``; a along x, b in the xy-plane."""
    a, b, c, alpha, beta, gamma = cell
    ca, cb, cg = (math.cos(math.radians(x)) for x in (alpha, beta, gamma))
    sg = math.sin(math.radians(gamma))
    radicand = 1.0 - ca * ca - cb * cb - cg * cg + 2.0 * ca * cb * cg
    if radicand <= 0 or sg == 0:
        raise ValueError(f"Degenerate cell {cell}")
    volume = a * b * c * math.sqrt(radicand)
    return (
        (a, b * cg, c * cb),
        (0.0, b * sg, c * (ca - cb * cg) / sg),
        (0.0, 0.0, volume / (a * b * sg)),
    )


def frac_to_cart(
    matrix: tuple[tuple[float, float, float], ...], frac: tuple[float, float, float]
) -> tuple[float, float, float]:
    x, y, z = frac
    return (
        matrix[0][0] * x + matrix[0][1] * y + matrix[0][2] * z,
        matrix[1][0] * x + matrix[1][1] * y + matrix[1][2] * z,
        matrix[2][0] * x + matrix[2][1] * y + matrix[2][2] * z,
    )


def u_equivalent(
    cell: tuple[float, float, float, float, float, float], u: tuple[float, ...]
) -> float | None:
    """U(eq) as one third of the trace of the orthogonalised tensor (Fischer & Tillmanns, 1988).

    Accepts SHELX order ``U11 U22 U33 U23 U13 U12``. Returns ``None`` for anything but six values.
    """
    if len(u) != 6:
        return None
    a, b, c, alpha, beta, gamma = cell
    ca, cb, cg = (math.cos(math.radians(x)) for x in (alpha, beta, gamma))
    sa, sb, sg = (math.sin(math.radians(x)) for x in (alpha, beta, gamma))
    volume = a * b * c * math.sqrt(1 - ca * ca - cb * cb - cg * cg + 2 * ca * cb * cg)
    a_s, b_s, c_s = b * c * sa / volume, a * c * sb / volume, a * b * sg / volume
    u11, u22, u33, u23, u13, u12 = u
    return (
        u11 * (a * a_s) ** 2
        + u22 * (b * b_s) ** 2
        + u33 * (c * c_s) ** 2
        + 2 * u12 * a * b * a_s * b_s * cg
        + 2 * u13 * a * c * a_s * c_s * cb
        + 2 * u23 * b * c * b_s * c_s * ca
    ) / 3.0


@dataclass(frozen=True)
class _Site:
    label: str
    element: str
    frac: tuple[float, float, float]
    kind: str


def _radius(element: str) -> float:
    return COVALENT_RADII.get(element, _DEFAULT_RADIUS)


def _distance(m, f1, f2, shift=(0, 0, 0)) -> float:
    d = tuple(f2[i] + shift[i] - f1[i] for i in range(3))
    x, y, z = frac_to_cart(m, d)
    return math.sqrt(x * x + y * y + z * z)


def build_viewer_payload(res: ResFile, *, stage: str, source_label: str = "") -> dict:
    """Everything the frontend needs to draw this model, and to say what it is drawing."""
    header = res.header
    if header.cell is None:
        raise ValueError("The model file has no CELL record; it cannot be displayed in 3D.")
    cell = (
        header.cell.a, header.cell.b, header.cell.c,
        header.cell.alpha, header.cell.beta, header.cell.gamma,
    )
    m = orthogonalisation_matrix(cell)

    atoms: list[dict] = []
    sites: list[_Site] = []
    for atom in res.atoms:
        element = res.element_of(atom).strip().capitalize()
        try:
            atomic_number(element)
            kind = "atom"
        except KeyError:
            kind = "unknown"
        frac = tuple(_strip_free_variable(v) for v in (atom.x, atom.y, atom.z))
        sites.append(_Site(atom.label, element, frac, kind))
        atoms.append(
            {
                "label": atom.label,
                "element": element if kind == "atom" else (element or "?"),
                "kind": kind,
                "frac": [round(v, 5) for v in frac],
                "cart": [round(v, 4) for v in frac_to_cart(m, frac)],
                "occupancy": round(atom.occupancy, 4),
                "occupancy_fixed": atom.occupancy_is_fixed,
                "u_iso": atom.u_iso,
                "u_eq": u_equivalent(cell, atom.u_values) if atom.is_anisotropic else None,
                "anisotropic": atom.is_anisotropic,
                "colour": ELEMENT_COLOURS.get(element, UNKNOWN_COLOUR),
                "radius": _radius(element),
            }
        )
    for peak in res.q_peaks:
        frac = tuple(_strip_free_variable(v) for v in (peak.x, peak.y, peak.z))
        sites.append(_Site(peak.label, "Q", frac, "q_peak"))
        atoms.append(
            {
                "label": peak.label,
                "element": "Q",
                "kind": "q_peak",
                "frac": [round(v, 5) for v in frac],
                "cart": [round(v, 4) for v in frac_to_cart(m, frac)],
                "height": peak.height,
                "rank": peak.rank,
                "occupancy": None,
                "u_iso": None,
                "colour": "#D946EF",
                "radius": 0.35,
            }
        )

    bonds, boundary, search = _contacts(cell, m, sites)

    corners = [(x, y, z) for x in (0, 1) for y in (0, 1) for z in (0, 1)]
    edges = [
        [list(frac_to_cart(m, p)), list(frac_to_cart(m, q))]
        for p in corners
        for q in corners
        if sum(abs(p[k] - q[k]) for k in range(3)) == 1 and p < q
    ]
    return {
        "schema": "crystalx.viewer/1",
        "stage": stage,
        "source": source_label or (res.source.name if isinstance(res.source, Path) else ""),
        "display": "asymmetric_unit",
        "display_note": (
            "Atoms as written in the model file (the asymmetric unit). No symmetry expansion. "
            "Lines are a display heuristic (covalent radii + 0.40 A), not evidence of chemical "
            "connectivity. They are drawn only between atoms as written (no lattice translation); "
            "contacts to lattice-translated copies are found by Cartesian distance over every "
            "translation that could reach bonding distance, and are listed and counted, not drawn. "
            "Symmetry-equivalent contacts are not searched."
        ),
        "element_note": (
            "Elements are those assigned by the solution/refinement program from peak heights. "
            "They are not independently verified."
        ),
        "confidence": {
            "available": False,
            "reason": (
                "No calibrated uncertainty estimate exists for this model. Occupancy and "
                "displacement parameters are shown as their own quantities, not as confidence."
            ),
        },
        "cell": dict(zip(("a", "b", "c", "alpha", "beta", "gamma"), cell)),
        "cell_edges": edges,
        "atoms": atoms,
        "bonds": bonds,
        "boundary_bonds": boundary,
        "contact_search": search,
        "counts": {
            "atoms": sum(1 for a in atoms if a["kind"] == "atom"),
            "unknown_sites": sum(1 for a in atoms if a["kind"] == "unknown"),
            "q_peaks": sum(1 for a in atoms if a["kind"] == "q_peak"),
            "bonds_drawn": len(bonds),
            "boundary_bonds_not_drawn": len(boundary),
        },
    }


#: Upper bound on the translations searched along one axis. Only a pathologically flat cell or a
#: model spread over many cells reaches it; the payload then says the search was truncated.
CONTACT_SEARCH_CAP = 8


def contact_search_extents(
    cell: tuple[float, float, float, float, float, float],
    fractional: list[tuple[float, float, float]],
    max_distance: float,
) -> tuple[tuple[int, int, int], bool]:
    """Translations to search along each axis so that no contact up to ``max_distance`` is missed.

    For fractional difference ``g = df + t`` and Cartesian vector ``r``, ``g_i = a*_i . r``, so
    ``|g_i| <= |a*_i| |r|``. With ``|df_i| <= R_i`` (the spread of the sites along axis *i*) a
    contact of length at most ``max_distance`` needs ``|t_i| <= R_i + max_distance |a*_i|``.
    Returns the extents and whether they are complete (``False`` when capped).
    """
    a, b, c, alpha, beta, gamma = cell
    ca, cb, cg = (math.cos(math.radians(x)) for x in (alpha, beta, gamma))
    sa, sb, sg = (math.sin(math.radians(x)) for x in (alpha, beta, gamma))
    volume = a * b * c * math.sqrt(max(1.0 - ca * ca - cb * cb - cg * cg + 2.0 * ca * cb * cg, 0.0))
    if volume <= 0:
        raise ValueError(f"Degenerate cell {cell}")
    reciprocal = (b * c * sa / volume, a * c * sb / volume, a * b * sg / volume)
    extents = []
    for axis in range(3):
        values = [f[axis] for f in fractional] or [0.0]
        spread = max(values) - min(values)
        extents.append(math.ceil(spread + max_distance * reciprocal[axis] - 1e-9))
    capped = tuple(min(max(n, 1), CONTACT_SEARCH_CAP) for n in extents)
    return capped, all(n <= CONTACT_SEARCH_CAP for n in extents)


def _contacts(cell, m, sites: list[_Site]) -> tuple[list[list], list[dict], dict]:
    """Bonds within one translation, and contacts to translated copies, by a grid search.

    Every site (Q peaks excluded) is placed in every translation of the search box; candidates are
    bucketed on a grid whose spacing is the largest possible bond length, so each site is compared
    only with nearby images. Pairs are reported once (i < j; or i == j for a site and its own
    translated copy, with the translation taken positive-first).
    """
    real = [i for i, s in enumerate(sites) if s.kind != "q_peak"]
    if not real:
        return [], [], {"translations_per_axis": [0, 0, 0], "complete": True}
    max_radius = max(_radius(sites[i].element) for i in real)
    spacing = 2 * max_radius + BOND_TOLERANCE_A
    (na, nb, nc), complete = contact_search_extents(cell, [sites[i].frac for i in real], spacing)
    translations = [
        (a, b, c)
        for a in range(-na, na + 1)
        for b in range(-nb, nb + 1)
        for c in range(-nc, nc + 1)
    ]
    grid: dict[tuple[int, int, int], list[tuple[int, tuple[int, int, int], tuple[float, float, float]]]] = {}
    for j in real:
        f = sites[j].frac
        for t in translations:
            cart = frac_to_cart(m, (f[0] + t[0], f[1] + t[1], f[2] + t[2]))
            key = (math.floor(cart[0] / spacing), math.floor(cart[1] / spacing), math.floor(cart[2] / spacing))
            grid.setdefault(key, []).append((j, t, cart))
    bonds: list[list] = []
    boundary: list[dict] = []
    for i in real:
        si = sites[i]
        ci = frac_to_cart(m, si.frac)
        key = (math.floor(ci[0] / spacing), math.floor(ci[1] / spacing), math.floor(ci[2] / spacing))
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                for dz in (-1, 0, 1):
                    for j, t, cj in grid.get((key[0] + dx, key[1] + dy, key[2] + dz), ()):
                        zero = t == (0, 0, 0)
                        if (zero and j <= i) or j < i or (j == i and t <= (0, 0, 0)):
                            continue
                        d = math.dist(ci, cj)
                        limit = _radius(si.element) + _radius(sites[j].element) + BOND_TOLERANCE_A
                        if not MIN_BOND_A <= d <= limit:
                            continue
                        if zero:
                            bonds.append([i, j, round(d, 3)])
                        else:
                            boundary.append(
                                {"a": si.label, "b": sites[j].label, "translation": list(t), "distance": round(d, 3)}
                            )
    bonds.sort()
    boundary.sort(key=lambda b: (b["a"], b["b"], b["distance"]))
    search = {
        "translations_per_axis": [na, nb, nc],
        "complete": complete,
        "note": (
            "every lattice translation that could bring two sites within bonding distance was tried"
            if complete
            else f"search capped at {CONTACT_SEARCH_CAP} cells per axis: some contacts may be missing"
        ),
    }
    return bonds, boundary, search


def _strip_free_variable(value: float) -> float:
    """SHELX writes a fixed coordinate as ``10 + x`` (or ``-10 + x``). Recover ``x``."""
    if value >= 5.0:
        return value - 10.0
    if value <= -5.0:
        return value + 10.0
    return value
